import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const PKG = join(import.meta.dirname, '..');
const CONTRACT = join(PKG, '..', 'API', 'docs', 'wire-contract.json');
const OUTPUT = join(PKG, 'src', 'generated', 'wireTypes.ts');
const checkOnly = process.argv.includes('--check');

function pascal(value) {
  return value
    .split(/[^A-Za-z0-9]+/)
    .filter((part) => part.length > 0)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
}

function quoteKey(key) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
}

function indent(text, levels) {
  const pad = '  '.repeat(levels);
  return text
    .split('\n')
    .map((line) => (line.length > 0 ? `${pad}${line}` : line))
    .join('\n');
}

function literal(value) {
  return JSON.stringify(value);
}

function renderObject(schema, depth) {
  const properties = schema.properties;
  const required = new Set(Array.isArray(schema.required) ? schema.required : []);
  const lines = [];
  if (properties !== undefined && typeof properties === 'object') {
    for (const [key, value] of Object.entries(properties)) {
      const optional = required.has(key) ? '' : '?';
      lines.push(`${quoteKey(key)}${optional}: ${render(value, depth + 1)};`);
    }
  }
  const additional = schema.additionalProperties;
  if (additional === true) lines.push('[key: string]: unknown;');
  else if (additional !== undefined && additional !== false) {
    lines.push(`[key: string]: ${render(additional, depth + 1)};`);
  }
  if (lines.length === 0) return 'Record<string, unknown>';
  return `{\n${indent(lines.join('\n'), 1)}\n}`;
}

function renderTuple(schema, depth) {
  const prefix = Array.isArray(schema.prefixItems) ? schema.prefixItems : [];
  const parts = prefix.map((item) => render(item, depth + 1));
  if (schema.items !== false && schema.items !== undefined) {
    parts.push(`...${render(schema.items, depth + 1)}[]`);
  }
  return `readonly [${parts.join(', ')}]`;
}

export function render(schema, depth = 0) {
  if (schema === null || schema === undefined) return 'void';
  if (typeof schema !== 'object') return 'unknown';
  if (Array.isArray(schema)) return 'unknown';
  if ('const' in schema) return literal(schema.const);
  if (Array.isArray(schema.enum)) return schema.enum.map((value) => literal(value)).join(' | ');
  if (Array.isArray(schema.anyOf)) {
    const union = schema.anyOf.map((item) => render(item, depth)).join(' | ');
    return union.length === 0 ? 'never' : union;
  }
  if (Array.isArray(schema.oneOf)) {
    const union = schema.oneOf.map((item) => render(item, depth)).join(' | ');
    return union.length === 0 ? 'never' : union;
  }
  if (Array.isArray(schema.type)) {
    return schema.type
      .map((member) =>
        member === 'null' ? 'null' : render({ ...schema, type: member }, depth),
      )
      .join(' | ');
  }
  if (schema.type === 'array') {
    if (Array.isArray(schema.prefixItems)) return renderTuple(schema, depth);
    return schema.items === undefined ? 'unknown[]' : `${render(schema.items, depth)}[]`;
  }
  if (schema.type === 'object' || schema.properties !== undefined) {
    return renderObject(schema, depth);
  }
  switch (schema.type) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    default:
      return 'unknown';
  }
}

export function renderWireTypes(contract) {
  const blocks = [
    '// Generated by scripts/gen-wire-types.mjs from packages/API/docs/wire-contract.json.',
    '// Do not edit by hand; run `pnpm --filter @hilbras/omnicode-client-contract gen:wire-types`.',
    '',
  ];
  for (const [service, methods] of Object.entries(contract.procedures)) {
    const serviceName = pascal(service);
    for (const [method, procedure] of Object.entries(methods)) {
      const methodName = pascal(method);
      blocks.push(
        `export type ${serviceName}${methodName}Input = ${render(procedure.input)};`,
        `export type ${serviceName}${methodName}Output = ${render(procedure.output ?? procedure.chunk)};`,
        '',
      );
    }
  }
  for (const [scope, events] of Object.entries(contract.events)) {
    for (const [name, event] of Object.entries(events)) {
      blocks.push(
        `export type ${pascal(scope)}${pascal(name)}Payload = ${render(event.schema)};`,
        '',
      );
    }
  }
  return `${blocks.join('\n').trimEnd()}\n`;
}

const contract = JSON.parse(readFileSync(CONTRACT, 'utf8'));
const rendered = renderWireTypes(contract);

if (checkOnly) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
  if (current !== rendered) {
    console.error(
      'wire types are stale — regenerate with pnpm --filter @hilbras/omnicode-client-contract gen:wire-types',
    );
    process.exit(1);
  }
  console.log(`wire types are fresh: ${OUTPUT}`);
} else {
  mkdirSync(dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, rendered);
  console.log(`wrote ${OUTPUT}`);
}
